# Создайте матрицу X размера 101 * 2. Значения в первом столбце должны быть равномерно распределены 
# в диапазоне [-3;13] (Значения в первом столбце образуют арифметическую прогрессию,  
# X[0][0]=-3, X[100][0]=13) 
# Значения во втором столбце X[i][1] вычисляются по формуле x^2-10x+21 где x --- значение из первого  
# столбца X[i][0] 
# Выведите строки матрицы от 40 до 60 
a = np.linspace(-3, 13, 101) 
b = a**2 - 10*a + 21 
X = (np.vstack((a,b))).T 
print (X[40:60]) 
 
print('----------4---------') 
# Нарисуйте на плоскости множество точек матрицы X, считая точкой с координатой (x,y) одну строку матрицы 
plt.scatter(X[:, 0], X[:, 1]) 
plt.title('4. Точки параболы') 
plt.xlabel('x') 
plt.ylabel('y') 
plt.grid(True) 
plt.show() 
