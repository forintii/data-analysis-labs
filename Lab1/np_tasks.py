# Создайте матрицу R поворота в двумерном пространстве для поворота на 30 градусов. 
# Посчитайте матрицу Y=XR 
# Выведите на графике кривую  по точкам из матрицы Y. 
t = np.radians(30) 
R = np.array([[np.cos(t), -np.sin(t)], 
              [np.sin(t), np.cos(t)]]) 
Y = X @ R 
 
plt.plot(Y[:, 0], Y[:, 1], 'r-') 
plt.title('6. Поворот на 30°') 
plt.xlabel('x') 
plt.ylabel('y') 
plt.grid(True) 
plt.axis('equal') 
plt.show() 
print('----------7---------') 
# Найдите обратную матрицу Q к матрице R. 
# Посчитайте матрицу Z=XQ 
Q = np.linalg.inv(R) 
Z = X @ Q 
 
plt.plot(Z[:, 0], Z[:, 1], 'g-') 
plt.title('7. Обратный поворот') 
plt.xlabel('x') 
plt.ylabel('y') 
plt.grid(True) 
plt.axis('equal') 
plt.show() 
print('----------8---------') 
# Выведите на одном графике три кривых: простую параболу и две параболы с поворотом. 
plt.plot(X[:, 0], X[:, 1], 'b-', label='Исходная') 
